def test_a_fork_compares_with_trayi_not_origin(clone, capsys, tmp_path):
    fork = tmp_path / "fork.git"
    git("init", "-q", "--bare", "-b", "main", str(fork), cwd=tmp_path)
    fork_url = "https://github.com/someone/trayi.git"
    git("config", f"url.{fork.as_uri()}.insteadOf", fork_url, cwd=clone)
    git("remote", "rename", "upstream", "dipbazz", cwd=clone)
    git("remote", "add", "origin", fork_url, cwd=clone)
    git("push", "-q", "origin", "main", cwd=clone)
    git("branch", "-q", "--set-upstream-to", "origin/main", cwd=clone)
    push_ahead(clone, remote="dipbazz")
    git("push", "-q", "--force", "origin", "main", cwd=clone)
    _, out = run(clone, capsys)
    assert line(out, "❌ main is 1 commit behind dipbazz/main")


