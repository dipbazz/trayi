def test_a_run_changes_no_branch_or_file(clone, capsys):
    push_ahead(clone)
    git("switch", "-q", "-c", "feat/1-thing", cwd=clone)
    before = [
        git("rev-parse", "HEAD", cwd=clone),
        git("for-each-ref", "refs/heads", cwd=clone),
        git("status", "--porcelain", "--ignored", cwd=clone),
    ]
    run(clone, capsys)
    after = [
        git("rev-parse", "HEAD", cwd=clone),
        git("for-each-ref", "refs/heads", cwd=clone),
        git("status", "--porcelain", "--ignored", cwd=clone),
    ]
    assert after == before


