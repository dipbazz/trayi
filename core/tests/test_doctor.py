"""The start-up check for a clone (scripts/doctor.py).

Each test builds a clone in tmp_path, with a local bare repository standing in for GitHub
(`url.<bare>.insteadOf`), and a fake uv that answers from a JSON file and logs its calls.
"""

import importlib.util
