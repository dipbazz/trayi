import pytest

PROJECT = Path(__file__).resolve().parents[2]
SCRIPT = PROJECT / "scripts" / "doctor.py"
spec = importlib.util.spec_from_file_location("doctor", SCRIPT)
doctor = importlib.util.module_from_spec(spec)
spec.loader.exec_module(doctor)

TRAYI = "https://github.com/dipbazz/trayi.git"
FAKE_UV = """
import json, os, sys
config = os.environ["FAKE_UV"]
with open(config + ".log", "a") as log:
    log.write(json.dumps(sys.argv[1:]) + "\\n")
answer = json.load(open(config)).get(sys.argv[1], {})
sys.stdout.write(answer.get("out", ""))
sys.stderr.write(answer.get("err", ""))
sys.exit(answer.get("code", 0))
"""


def git(*args, cwd):
    return subprocess.run(
        ["git", *args], cwd=cwd, check=True, capture_output=True, text=True
    ).stdout.strip()


@pytest.fixture(autouse=True)
def isolated_git(tmp_path, monkeypatch):
    """Keep the machine's own git config and any hook's GIT_DIR out of the tests."""
    empty = tmp_path / "gitconfig"
    empty.write_text("")
    monkeypatch.setenv("GIT_CONFIG_GLOBAL", str(empty))
    monkeypatch.setenv("GIT_CONFIG_NOSYSTEM", "1")
    monkeypatch.setenv("GIT_CEILING_DIRECTORIES", str(tmp_path))
    for name in ("GIT_DIR", "GIT_WORK_TREE", "GIT_INDEX_FILE", "GIT_SSH_COMMAND", "NO_COLOR"):
        monkeypatch.delenv(name, raising=False)


@pytest.fixture
def uv(tmp_path, monkeypatch):
    """A fake uv; set its answers with uv.answer(<first argument>, out=, err=, code=)."""
    script = tmp_path / "fake_uv.py"
    script.write_text(FAKE_UV)
    config = tmp_path / "fake_uv.json"
    answers = {"--version": {"out": "uv 0.9.24 (0fda1525e 2026-01-09)\n"}}
    config.write_text(json.dumps(answers))
    monkeypatch.setenv("FAKE_UV", str(config))
    monkeypatch.setattr(doctor, "uv_command", lambda: [sys.executable, str(script)])

    class Fake:
        def answer(self, key, **answer):
            answers[key] = answer
            config.write_text(json.dumps(answers))

        def calls(self):
            log = Path(f"{config}.log")
            if not log.exists():
                return []
            return [json.loads(line) for line in log.read_text().splitlines()]

    return Fake()


def install_hooks(folder, *names):
    folder.mkdir(parents=True, exist_ok=True)
    for name in names:
        (folder / name).write_text(
            "#!/usr/bin/env bash\n# File generated by pre-commit: https://pre-commit.com\n"
        )


@pytest.fixture
def github(tmp_path):
    """A bare repository standing in for github.com/dipbazz/trayi."""
    bare = tmp_path / "github.git"
    git("init", "-q", "--bare", "-b", "main", str(bare), cwd=tmp_path)
    return bare


@pytest.fixture
def clone(tmp_path, github, uv):
    """A set-up clone: identity, hooks, a database and the trayi remote, up to date."""
    repo = tmp_path / "clone"
    repo.mkdir()
    git("init", "-q", "-b", "main", cwd=repo)
    git("config", "user.name", "Test", cwd=repo)
    git("config", "user.email", "test@example.com", cwd=repo)
    git("config", "commit.gpgsign", "false", cwd=repo)
    (repo / ".pre-commit-config.yaml").write_text(
        "default_install_hook_types: [pre-commit, commit-msg]\n"
    )
    git("add", ".", cwd=repo)
    git("commit", "-q", "-m", "start", cwd=repo)
    install_hooks(repo / ".git" / "hooks", "pre-commit", "commit-msg")
    (repo / "db.sqlite3").write_text("")
    git("config", f"url.{github.as_uri()}.insteadOf", TRAYI, cwd=repo)
    git("remote", "add", "upstream", TRAYI, cwd=repo)
    git("push", "-q", "upstream", "main", cwd=repo)
    return repo


def push_ahead(repo, remote="upstream"):
    """Put one commit on <remote>'s main that the clone doesn't have."""
    git("commit", "-q", "--allow-empty", "-m", "newer", cwd=repo)
    git("push", "-q", remote, "HEAD:main", cwd=repo)
    git("reset", "-q", "--hard", "HEAD~1", cwd=repo)


def run(root, capsys, *args):
    code = doctor.main(list(args), root=root)
    return code, capsys.readouterr().out


def line(out, start):
    """The one output line starting with a symbol and containing a phrase."""
    return [text for text in out.splitlines() if start in text]


